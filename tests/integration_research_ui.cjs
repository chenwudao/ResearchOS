const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>d.accept());
  await page.goto('http://127.0.0.1:'+process.argv[2]);
  await page.locator('#workspace-status').getByText('已保存到本机').waitFor();
  await page.locator('#btn-new-project').click();
  await page.locator('#modal-input').fill('算法对照实验');
  await page.locator('#modal-ok').click();
  await page.locator('#btn-research-workflow').click();
  const panel=page.locator('#research-dialog');
  await panel.getByRole('button',{name:'编辑科研状态',exact:true}).click();
  await panel.getByLabel('核心研究问题',{exact:true}).fill('验证候选算法是否稳定优于基线');
  await panel.getByRole('button',{name:'保存确认',exact:true}).click();
  await panel.getByText('验证候选算法是否稳定优于基线',{exact:true}).waitFor();
  await panel.getByRole('button',{name:'实验工作流',exact:true}).click();
  await panel.getByRole('button',{name:'创建算法对照示例',exact:true}).click();
  await panel.getByRole('button',{name:'编辑计划',exact:true}).click();
  const input=panel.getByLabel('计划 JSON',{exact:true});
  const plan=JSON.parse(await input.inputValue());
  plan.matrix.seeds=[11,22,33];plan.matrix.budgets=[64];plan.budget.maxRuns=9;
  await input.fill(JSON.stringify(plan,null,2));
  await panel.getByRole('button',{name:'保存计划草案',exact:true}).click();
  await panel.getByRole('button',{name:'确认协议与预算',exact:true}).click();
  await panel.getByRole('button',{name:'开始执行',exact:true}).click();
  await panel.getByRole('button',{name:'确认结果并更新研究状态',exact:true}).waitFor({timeout:120000});
  await panel.getByRole('img',{name:'不同方法与样本预算的主指标均值和标准差'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'demo/.local/v3-workflow-ui.png',fullPage:true});
  const href=await panel.getByRole('link',{name:'导出全部实验 CSV'}).getAttribute('href');
  const exported=await page.request.get('http://127.0.0.1:'+process.argv[2]+href);
  assert.equal(exported.status(),200);
  assert.equal((await exported.text()).trim().split('\n').length,10);
  await panel.getByRole('button',{name:'确认结果并更新研究状态',exact:true}).click();
  await panel.getByRole('button',{name:'科研状态',exact:true}).click();
  await panel.getByText('结果已核查，待下一轮验证',{exact:true}).waitFor();
  assert.equal(await panel.getByText('部分关联证据已缺失或发生变化，需要重新核查。',{exact:true}).count(),0);
  await page.screenshot({path:'demo/.local/v3-state-ui.png',fullPage:true});
  await panel.getByRole('button',{name:'证据网络',exact:true}).click();
  await panel.getByRole('img',{name:'项目科研证据关系图'}).waitFor();
  await page.screenshot({path:'demo/.local/v3-evidence-ui.png',fullPage:true});
  await panel.getByRole('button',{name:'查看来源与关系'}).first().click();
  await panel.getByLabel('核查依据',{exact:true}).waitFor();
  await panel.getByRole('button',{name:'关闭',exact:true}).click();
  await page.reload();
  await page.locator('#btn-research-workflow').click();
  await panel.getByText('结果已核查，待下一轮验证',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('V3 browser plan editing, approval, execution, analysis, CSV export, evidence and reload passed');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
