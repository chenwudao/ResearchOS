const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require('playwright')
const url = fs.readFileSync(0, 'utf8').trim()

async function main() {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true })
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 820 } })
  const page = await context.newPage()
  page.setDefaultTimeout(18000)
  const button = name => page.getByRole('button', { name, exact: true })
  try {
    await context.route('https://example.org/**', route => route.fulfill({ body: 'fixture original' }))
    await page.goto(url, { waitUntil: 'domcontentloaded' })
    await button('稍后配置').click()
    const branch = page.getByRole('navigation', { name: '推送验证 项目功能' })
    if (!(await branch.isVisible())) await button('推送验证').click()
    await branch.getByRole('button', { name: '动态', exact: true }).click()
    const feed = page.getByRole('region', { name: '动态', exact: true })
    const card = feed.locator('.lw-fbot-card[data-illustrated="true"]')
    const image = card.locator('img')
    const footer = card.locator('footer')
    const link = footer.getByRole('link', { name: /查看原文/ })
    await image.evaluate(el => el.decode())
    assert.match(await footer.innerText(), /来源：实测期刊/)
    const [imageBox, cardBox, figureBox, footerBox] =
      await Promise.all([image, card, card.locator('figure'), footer].map(el => el.boundingBox()))
    assert.ok(imageBox.width > cardBox.width * .85 && imageBox.height > 100)
    assert.ok(footerBox.y >= figureBox.y + figureBox.height - 1)
    const [original] = await Promise.all([page.waitForEvent('popup'), link.click()])
    await original.getByText('fixture original').waitFor()
    assert.equal(original.url(), 'https://example.org/paper')
    await original.close()
    assert.equal(await feed.locator('.lw-fbot-detail').count(), 0)
    const textCard = feed.locator('.lw-fbot-card').filter({ hasText: '另一条无图动态' })
    assert.equal(await textCard.locator('img').count(), 0)
    assert.match(await textCard.locator('footer').innerText(), /来源：example.org/)

    await button('设置').click()
    await button('深色').click()
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 900, height: 700 })
    await page.evaluate(() => { document.documentElement.style.zoom = '125%' })
    await link.scrollIntoViewIfNeeded()
    const narrow = await link.boundingBox()
    assert.ok(narrow.x >= 0 && narrow.x + narrow.width <= 901)
    await card.getByRole('button', { name: '可读的实验插图', exact: true }).click()
    const detail = feed.locator('.lw-fbot-detail')
    await detail.locator('figcaption').getByText('实验观察图注', { exact: true }).waitFor()
    assert.match(await detail.locator('footer').innerText(), /来源：实测期刊/)
    assert.equal(await detail.locator('footer a').getAttribute('href'), 'https://example.org/paper')
    console.log('动态大图、图注、底部来源和原文链接验证通过，覆盖深色主题及 125% 缩放。')
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(String(error.stack).replaceAll(url, '[test login]')); process.exitCode = 1 })
