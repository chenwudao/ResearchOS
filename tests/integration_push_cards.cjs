const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')
const scoresPath = process.argv[2]
const url = fs.readFileSync(0, 'utf8').trim()

async function main() {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true })
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 820 }, reducedMotion: 'no-preference' })
  const page = await context.newPage()
  page.setDefaultTimeout(18000)
  const button = name => page.getByRole('button', { name, exact: true })
  try {
    await context.route('https://example.org/**', route => route.fulfill({ body: 'fixture original' }))
    await page.goto(url, { waitUntil: 'domcontentloaded' })
    await button('稍后配置').click()
    const branch = page.getByRole('navigation', { name: '推送验证 项目功能' })
    if (!(await branch.isVisible())) await button('推送验证').click()
    await branch.getByRole('button', { name: '动态', exact: true }).click()
    const feed = page.getByRole('region', { name: '动态', exact: true })
    const card = feed.locator('.lw-canvas-card').filter({ hasText: '可读的实验插图' })
    await card.locator('img').evaluate(el => el.decode())
    await card.getByText('同一条件下比较了两种测评结果。', { exact: true }).waitFor()
    assert.equal(await card.getByText(/证据等级/).count(), 0)
    const textCard = feed.locator('.lw-canvas-card').filter({ hasText: '另一条无图动态' })
    assert.equal(await textCard.locator('img').count(), 0)

    await button('设置').click()
    await button('深色').click()
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 900, height: 700 })
    await page.evaluate(() => { document.documentElement.style.zoom = '125%' })
    await card.getByRole('button', { name: '可读的实验插图', exact: true }).click()
    const detail = page.getByRole('dialog', { name: '动态详情' })
    const narrow = await detail.boundingBox()
    assert.ok(narrow.x >= 0 && narrow.x + narrow.width <= 901)
    await detail.getByRole('heading', { name: '可读的实验插图', level: 2 }).waitFor()
    assert.deepEqual(await detail.locator('.lw-record-section h3').allTextContents(), ['方法', '结论', '局限', '证据等级'])
    assert.equal(await detail.locator('[data-kind="finding"] strong').innerText(), '方法排序')
    assert.equal(await detail.locator('pre code').innerText(), '方法：这是原样保留的代码块')
    const media = detail.getByRole('region', { name: '配图与图表' })
    const plot = media.getByRole('img', { name: /准确率曲线.*折线图/ })
    await plot.scrollIntoViewIfNeeded()
    const area = await plot.boundingBox()
    await page.mouse.move(area.x + area.width * .85, area.y + area.height / 2)
    await media.getByText('步 3 · 准确率 0.9', { exact: true }).waitFor()
    await media.getByRole('slider', { name: '查看数据点' }).press('Home')
    await media.getByText('步 1 · 准确率 0.7', { exact: true }).waitFor()
    await media.getByRole('button', { name: '配图', exact: true }).click()
    await media.locator('figcaption').getByText('实验观察图注', { exact: true }).waitFor()
    await media.getByRole('button', { name: '交互图表', exact: true }).click()
    await media.getByRole('group', { name: '图表类型' }).getByRole('button', { name: '散点图', exact: true }).click()
    await media.getByRole('img', { name: /准确率曲线.*散点图/ }).waitFor()
    assert.match(await detail.locator('footer').innerText(), /来源：实测期刊/)
    assert.equal(await detail.locator('footer a').getAttribute('href'), 'https://example.org/paper')
    if (process.env.LABWEAVE_PREVIEW_DIR) {
      await detail.screenshot({ path: path.join(process.env.LABWEAVE_PREVIEW_DIR, 'weave-record-detail.png') })
    }
    await detail.getByRole('button', { name: '在弹窗中浏览原文' }).click()
    await detail.frameLocator('iframe').getByText('fixture original').waitFor()
    assert.equal(await detail.getByRole('link', { name: '在新标签页打开' }).getAttribute('href'), 'https://example.org/paper')
    await detail.getByRole('button', { name: '关闭 动态详情' }).click()
    await page.evaluate(() => { document.documentElement.style.zoom = '' })
    await page.setViewportSize({ width: 1280, height: 820 })
    await branch.getByRole('button', { name: '文献脉络', exact: true }).click()
    await page.getByRole('main', { name: '推送验证的文献脉络' })
      .getByRole('button', { name: '两种评测设置的比较', exact: true }).click()
    const record = page.getByRole('dialog', { name: '记录详情', exact: true })
    await record.getByRole('heading', { name: '两种评测设置的比较', level: 2 }).waitFor()
    assert.deepEqual(await record.locator('.lw-record-markdown li').allTextContents(), ['条件一', '条件二'])
    await page.keyboard.press('Escape')
    await button('数据附件').click()
    await record.getByRole('img', { name: /accuracy.*折线图.*step/ }).waitFor()
    await record.getByRole('combobox', { name: '图表类型' }).click()
    await page.getByRole('option', { name: '散点图', exact: true }).click()
    await record.getByRole('img', { name: /accuracy.*散点图/ }).waitFor()
    await page.keyboard.press('Escape')

    const star = page.locator('.lw-bot-canvas[data-layout="star"]')
    await branch.getByRole('button', { name: '方法关系图', exact: true }).click()
    await star.locator('[data-hub="true"]').getByText('中心方法').waitFor()
    await star.locator('.lw-canvas-edges path').waitFor({ state: 'attached' })
    assert.ok(await star.locator('.lw-canvas-edges path').evaluate(path =>
      path.getTotalLength() > 0 && parseFloat(getComputedStyle(path).strokeWidth) > 1))
    assert.match(await star.locator('[data-kind="branch"] path').first().getAttribute('marker-end'), /^url\(#/)
    await star.getByRole('button', { name: '编辑连线 外部证据', exact: true }).click()
    const crossLink = page.getByRole('dialog', { name: '编辑连线', exact: true })
    await crossLink.getByRole('combobox', { name: '上级节点' }).click()
    await page.getByRole('option', { name: '方法关系图 · 中心方法', exact: true }).click()
    await crossLink.getByRole('button', { name: '保存连线', exact: true }).click()
    const linked = await star.locator('[data-canvas-node]').filter({ hasText: '外部证据' }).getAttribute('data-canvas-node')
    await star.locator('[data-kind="branch"][data-to="' + linked + '"] path[marker-end]').waitFor({ state: 'attached' })
    const add = page.getByRole('dialog', { name: '添加分支', exact: true })
    await star.getByRole('button', { name: '放大画布', exact: true }).click()
    await star.getByRole('button', { name: '添加分支 中心方法', exact: true }).click()
    await add.getByLabel('节点标题').fill('方法分支')
    await star.locator('.lw-canvas-viewport').evaluate(viewport => {
      const samples = []
      viewport.scrollTo(0, 0)
      const deadline = performance.now() + 5000
      window.branchCenteringSamples = new Promise(resolve => {
        function sample(now) {
          const card = viewport.querySelector('button[aria-label="方法分支"]')?.closest('[data-canvas-node]')
          if (card) {
            const frame = viewport.getBoundingClientRect()
            const rect = card.getBoundingClientRect()
            const distance = Math.hypot(rect.left + rect.width / 2 - frame.left - frame.width / 2,
              rect.top + rect.height / 2 - frame.top - frame.height / 2)
            samples.push(distance)
            if (distance < 3) return resolve(samples)
          }
          if (now >= deadline) return resolve(samples)
          requestAnimationFrame(sample)
        }
        requestAnimationFrame(sample)
      })
    })
    await add.getByRole('button', { name: '保存节点', exact: true }).click()
    const distances = await page.evaluate(() => window.branchCenteringSamples)
    assert.ok(distances.at(-1) < 3, distances.join(', '))
    assert.ok(new Set(distances.map(Math.round)).size >= 3, distances.join(', '))
    assert.equal(await star.locator('[aria-label="当前缩放"]').innerText(), '110%')
    await star.getByRole('button', { name: '编辑连线 对照方法', exact: true }).click()
    const connect = page.getByRole('dialog', { name: '编辑连线', exact: true })
    await connect.getByRole('checkbox', { name: '方法关系图 · 候选方法', exact: true }).check()
    await connect.getByRole('button', { name: '保存连线', exact: true }).click()
    await star.locator('[data-kind="related"] path').waitFor({ state: 'attached' })
    await page.setViewportSize({ width: 900, height: 700 })
    await page.evaluate(() => { document.documentElement.style.zoom = '125%' })
    await star.getByRole('button', { name: '全屏画布', exact: true }).click()
    await page.getByRole('dialog', { name: '全屏画布', exact: true }).getByRole('button', {
      name: '删除节点 候选方法', exact: true,
    }).click()
    await page.getByRole('dialog', { name: '删除节点', exact: true }).getByRole('button', { name: '确认删除' }).click()
    await star.locator('[data-kind="related"] path').waitFor({ state: 'detached' })
    await page.getByRole('button', { name: '关闭 全屏画布', exact: true }).click()
    await page.evaluate(() => { document.documentElement.style.zoom = '' })
    await page.setViewportSize({ width: 1280, height: 820 })
    await branch.getByRole('button', { name: '数据总线', exact: true }).click()
    const bus = page.locator('.lw-bot-canvas[data-layout="bus"]')
    assert.match(await bus.locator('.lw-canvas-edges path').getAttribute('d'), /V.*H.*V/)

    await branch.getByRole('button', { name: '运行追踪', exact: true }).click()
    const executionCanvas = page.locator('.lw-bot-canvas[data-layout="sequence"]')
    await executionCanvas.getByText('loss 0.4', { exact: true }).waitFor()
    const stage = executionCanvas.locator('.lw-canvas-stage')
    const beforeMetricUpdate = await stage.evaluate(element => element.style.transform)
    fs.appendFileSync(scoresPath, '7,0.3\n')
    await executionCanvas.getByText('loss 0.3', { exact: true }).waitFor()
    assert.equal(await stage.evaluate(element => element.style.transform), beforeMetricUpdate)
    await button('训练曲线').click()
    const experiment = page.getByRole('region', { name: '实验详情', exact: true })
    await experiment.getByRole('img', { name: /loss.*折线图.*step/ }).waitFor()
    await experiment.getByRole('button', { name: '最小化画布', exact: true }).click()
    await experiment.waitFor({ state: 'hidden' })
    await button('显示画布').click()
    await experiment.getByRole('img', { name: /loss.*折线图.*step/ }).waitFor()
    await experiment.getByRole('button', { name: 'scores.csv', exact: true }).click()
    const artifactPlot = experiment.locator('figure.lw-bot-chart').filter({
      has: page.getByRole('combobox', { name: '图表类型', exact: true }),
    })
    await artifactPlot.getByRole('slider').press('End')
    await artifactPlot.getByText('step 7 · loss 0.3', { exact: true }).waitFor()
    fs.appendFileSync(scoresPath, '9,0.2\n')
    await page.waitForFunction(() => document.querySelectorAll('.lw-bot-chart-inspect input')[1]?.max === '3')
    await artifactPlot.getByRole('slider').press('End')
    await artifactPlot.getByText('step 9 · loss 0.2', { exact: true }).waitFor()
    await experiment.getByRole('button', { name: '返回实验', exact: true }).click()
    await executionCanvas.getByRole('button', { name: '添加分支 训练曲线', exact: true }).click()
    await add.getByLabel('节点标题').fill('复核指标')
    await add.getByRole('button', { name: '保存节点', exact: true }).click()
    await executionCanvas.locator('.lw-canvas-edges path').waitFor({ state: 'attached' })
    await executionCanvas.getByRole('button', { name: '删除节点 训练曲线', exact: true }).click()
    await page.getByRole('dialog', { name: '删除节点', exact: true }).getByRole('button', { name: '确认删除' }).click()
    await executionCanvas.getByRole('button', { name: '训练曲线', exact: true }).waitFor({ state: 'detached' })
    await executionCanvas.getByRole('button', { name: '复核指标', exact: true }).waitFor()
    assert.ok(fs.existsSync(scoresPath))
    console.log('节点增删、关联线、星形和总线、动态和附件图表、运行产物刷新验证通过。')
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(String(error.stack).replaceAll(url, '[test login]')); process.exitCode = 1 })
