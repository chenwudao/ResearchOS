const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
const { readFileSync } = require('node:fs')
const { chromium } = require('playwright')

async function main() {
  const url = readFileSync(0, 'utf8').trim()
  const [python, fixture, data] = process.argv.slice(2)
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || (process.platform === 'win32' ? 'msedge' : 'chromium') })
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1360, height: 850 } })
  const errors = []
  const consoleErrors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  try {
    page.setDefaultTimeout(12000)
    const button = (target, name) => target.getByRole('button', { name, exact: true })
    const planner = page.getByRole('region', { name: '目标日历与待办' })
    const agenda = planner.getByRole('complementary', { name: '待办' })
    const nav = page.getByRole('navigation', { name: '排期验收 项目功能' })
    const task = '整理同机位渲染对照'
    const setup = page.getByRole('dialog', { name: '配置模型 API' })
    async function dismissSetup() {
      await setup.waitFor()
      await button(setup, '稍后配置').click()
      await setup.waitFor({ state: 'hidden' })
    }
    async function openGoals() {
      if (!await nav.isVisible()) await button(page, '排期验收').click()
      await button(nav, '实验排期').click()
      await planner.waitFor()
    }
    async function createBot(paradigm, name) {
      await button(page, '在排期验收创建功能 Bot').click()
      const form = page.getByRole('dialog', { name: '创建功能 Bot' })
      await form.getByRole('radio', { name: paradigm, exact: true }).check()
      await form.getByLabel('名字').fill(name)
      await button(form, '创建').click()
      await form.waitFor({ state: 'hidden' })
    }
    await page.goto(url)
    await page.locator('.lw-wordmark').waitFor()
    await dismissSetup()
    await button(page, '新建工作区项目').click()
    const projectForm = page.getByRole('dialog', { name: '新建工作区项目' })
    await projectForm.getByLabel('项目名称').fill('排期验收')
    await button(projectForm, '创建').click()
    await nav.waitFor()
    await createBot('目标', '实验排期')
    await openGoals()
    const dates = await planner.locator('.lw-goal-day > button').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))
    assert.equal(dates.length, 7)
    await button(planner, dates[0]).click()
    await agenda.getByRole('textbox', { name: '新待办名称' }).fill(task)
    await agenda.getByRole('textbox', { name: '所属阶段' }).fill('实验验证')
    await agenda.getByLabel('截止日期', { exact: true }).fill(dates[6])
    await agenda.getByRole('checkbox', { name: '标记为里程碑' }).check()
    await button(agenda, '添加待办').click()
    await button(agenda, task).waitFor()
    await agenda.getByText('里程碑', { exact: true }).waitFor()
    await agenda.getByLabel('安排日期 ' + task).fill(dates[1])
    await button(planner, dates[1]).click()
    await button(agenda, task).waitFor()
    assert.equal(await agenda.getByText('截止 ' + dates[6]).count(), 1)
    await agenda.getByRole('checkbox', { name: '完成 ' + task }).click()
    await agenda.locator('input[type=checkbox]:checked').waitFor()
    await button(planner, '看板').click()
    await planner.locator('.lw-goal-board section').filter({ has: page.getByRole('heading', { name: '已完成' }) })
      .getByRole('button', { name: task }).waitFor()

    await page.reload()
    await dismissSetup()
    if (!await planner.isVisible()) await openGoals()
    await button(planner, dates[1]).click()
    await button(agenda, task).waitFor()
    assert.equal(await agenda.getByLabel('安排日期 ' + task).inputValue(), dates[1])
    assert.equal(await agenda.getByRole('checkbox', { name: '完成 ' + task }).isChecked(), true)
    await button(planner, '月').click()
    assert.equal(await planner.locator('.lw-goal-day').count(), 42)
    await button(planner, '日').click()
    assert.equal(await planner.locator('.lw-goal-day').count(), 1)

    execFileSync(python, [fixture, '--suggest', data, dates[1]], { timeout: 10000 })
    const proposals = planner.getByRole('region', { name: '待确认排期' })
    await button(proposals, '采纳 核对评分表').waitFor()
    assert.equal(await agenda.getByRole('checkbox', { name: '完成 核对评分表' }).count(), 0)
    assert.equal(await planner.getByRole('progressbar', { name: '实验验证 完成进度' }).getAttribute('max'), '1')
    await button(proposals, '忽略 检查额外资料').click()
    await button(proposals, '忽略 检查额外资料').waitFor({ state: 'detached' })
    await button(proposals, '采纳 核对评分表').click()
    await proposals.waitFor({ state: 'detached' })
    await agenda.getByRole('checkbox', { name: '完成 核对评分表' }).waitFor()
    assert.equal(await planner.getByRole('progressbar', { name: '实验验证 完成进度' }).getAttribute('max'), '2')

    await page.setViewportSize({ width: 900, height: 760 })
    await page.locator('html').evaluate(node => { node.style.zoom = '1.15' })
    const columns = planner.locator('.lw-goal-columns')
    assert.equal(await columns.evaluate(node => node.scrollWidth <= node.clientWidth + 1), true)
    await page.locator('html').evaluate(node => { node.style.zoom = '' })
    await page.setViewportSize({ width: 1360, height: 850 })
    await createBot('笔记', '实验日志')
    const notePage = page.getByRole('main', { name: '排期验收的实验日志' })
    const noteName = '凉亭广场的对照记录'
    const initialNote = '本轮保留原机位，只比较已有渲染。'
    const noteContext = notePage.getByRole('complementary', { name: '笔记附件与关联' })
    await button(notePage, '新增目录').click()
    await notePage.getByLabel('目录名称').fill('实验/反馈')
    await button(notePage, '保存目录').click()
    await button(notePage, '反馈').waitFor()
    await button(notePage, '新建笔记').click()
    await notePage.getByLabel('笔记标题').fill(noteName)
    await notePage.getByLabel('标签', { exact: true }).fill('3D, 复验')
    await notePage.getByLabel('笔记内容').fill('# 研究观察\n\n' + initialNote +
      '\n\n| 方法 | 总分 |\n| --- | --- |\n| R2 | 65.29 |\n\n误差 $x^2$。')
    await button(notePage, '预览笔记').click()
    assert.equal(await notePage.getByRole('table').count(), 1)
    assert.equal(await notePage.locator('math msup').count(), 1)
    await button(notePage, '保存笔记').click()
    await notePage.getByRole('heading', { name: noteName }).waitFor()
    await noteContext.locator('input[type=file]').setInputFiles({
      name: 'evaluation.csv', mimeType: 'text/csv', buffer: Buffer.from('stage,score\nR2,65.29\n'),
    })
    await button(noteContext, 'evaluation.csv').click()
    await page.getByRole('dialog').getByText('stage,score', { exact: false }).waitFor()
    await page.keyboard.press('Escape')
    await button(notePage, '编辑笔记').click()
    await notePage.getByLabel('笔记内容').fill('加入扣分项和独立复验。')
    await button(notePage, '保存笔记').click()
    await notePage.getByText('加入扣分项和独立复验。', { exact: true }).waitFor()
    await button(notePage, '查看版本历史').click()
    await notePage.getByText(/^第 1 版/).click()
    await notePage.getByText(initialNote, { exact: true }).waitFor()
    await button(notePage, '新建笔记').click()
    await notePage.getByLabel('笔记标题').fill('第二篇笔记')
    await notePage.getByLabel('笔记内容').fill('复用同一份评分原件。')
    await button(notePage, '保存笔记').click()
    await notePage.getByRole('heading', { name: '第二篇笔记' }).waitFor()
    await noteContext.getByLabel('选择项目资料').selectOption({ label: 'evaluation.csv' })
    await button(noteContext, '关联附件').click()
    await button(noteContext, 'evaluation.csv').waitFor()
    await button(notePage, noteName).click()
    const links = page.getByRole('region', { name: '关联项目记录' })
    await links.getByLabel('选择项目记录').selectOption({ label: task })
    await button(links, '添加关联').click()
    await button(links, '实验排期 · ' + task).click()
    await planner.waitFor()
    await links.getByRole('heading', { name: '被这些记录引用' }).waitFor()
    await button(links, '实验日志 · ' + noteName).click()
    await notePage.waitFor()
    await button(links, '移除关联 ' + task).click()
    await button(links, '实验排期 · ' + task).waitFor({ state: 'detached' })
    assert.deepEqual(errors, [])
    console.log('Calendar, notebook editing/preview/history, attachment reuse and two-way record navigation passed.')
  } catch (error) {
    console.error({ title: await page.title(), body: (await page.locator('body').innerText()).slice(0, 600), errors, consoleErrors })
    throw error
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
