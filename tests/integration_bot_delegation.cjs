const fs = require('node:fs')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')

async function main() {
  const { url, releaseUrl, groupId, memberId } = JSON.parse(fs.readFileSync(0, 'utf8'))
  const channel = process.env.PLAYWRIGHT_CHANNEL || (process.platform === 'win32' ? 'msedge' : 'chromium')
  const browser = await chromium.launch({ channel, headless: true })
  try {
    const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 820 } })
    const page = await context.newPage()
    page.setDefaultTimeout(30000)
    page.on('pageerror', error => console.error(error.message))
    await page.goto(url, { waitUntil: 'domcontentloaded' })
    const nav = page.getByRole('navigation', { name: '分派验收项目 项目功能' })
    if (!await nav.isVisible()) await page.getByRole('button', { name: '分派验收项目', exact: true }).click()
    await nav.getByRole('button', { name: '聊天', exact: true }).click()
    const chat = page.locator('[data-conversation-content][data-conversation-session]:visible').last()
    const input = chat.locator('[contenteditable=true]').last()
    if (!await input.waitFor({ timeout: 8000 }).then(() => true, () => false)) {
      await nav.getByRole('button', { name: '在分派验收项目中新建对话', exact: true }).click()
    }
    await input.fill('请把两个独立的资料核对任务交给项目 Bot。WEAVE_DELEGATION_PROBE')
    await chat.getByRole('button', { name: '发送消息', exact: true }).click()
    try {
      const toggle = page.getByRole('button', { name: '项目任务', exact: true })
      await toggle.click()
      const tasks = page.getByRole('dialog', { name: '项目任务', exact: true })
      await tasks.getByText('执行中', { exact: true }).nth(1).waitFor({ timeout: 100000 })
      await tasks.getByRole('heading', { name: '原文核对', exact: true }).waitFor()
      await tasks.getByRole('heading', { name: '证据关系', exact: true }).waitFor()
      const board = await context.newPage()
      board.setDefaultTimeout(30000)
      await board.goto(url, { waitUntil: 'domcontentloaded' })
      await board.getByRole('button', { name: '证据关系', exact: true }).click()
      const canvas = board.getByRole('region', { name: '文献与方法关系图', exact: true })
      await canvas.getByText('实时草稿 PAPER_BETA', { exact: true }).waitFor({ timeout: 65000 })
      await canvas.getByText('草稿 · 待核验', { exact: true }).waitFor()
      assert.equal(await tasks.getByText('已完成', { exact: true }).count(), 0)
      assert.ok((await fetch(releaseUrl)).ok)
      await canvas.getByRole('button', { name: '对照总览', exact: true }).click()
      const inspector = board.getByRole('complementary', { name: '节点详情' })
      await inspector.getByRole('button', { name: '添加分支', exact: true }).click()
      await inspector.getByLabel('节点名称').fill('对照子节点')
      await inspector.getByRole('button', { name: '保存节点', exact: true }).click()
      await canvas.getByRole('button', { name: '全屏画布', exact: true }).click()
      const full = board.getByRole('dialog', { name: '全屏画布', exact: true })
      const card = full.locator('[data-canvas-node]').filter({ hasText: '对照子节点' })
      await card.waitFor()
      const edge = full.locator('.lw-canvas-edges path').first()
      await edge.waitFor({ state: 'attached' })
      await board.setViewportSize({ width: 850, height: 720 })
      await board.evaluate(() => { document.body.style.zoom = '1.25' })
      const viewport = await full.boundingBox()
      assert.ok(viewport && viewport.x >= 0 && viewport.x + viewport.width <= 851)
      const curve = await edge.getAttribute('d')
      const bounds = await card.boundingBox()
      await full.getByRole('button', { name: '放大画布', exact: true }).click()
      const scaled = await card.boundingBox()
      assert.ok(Math.abs(scaled.width / bounds.width - 1.1) < .015)
      assert.equal(await edge.getAttribute('d'), curve)
      await full.getByRole('button', { name: '关闭 全屏画布', exact: true }).click()
      await canvas.getByRole('button', { name: '对照子节点', exact: true }).click()
      await inspector.getByRole('button', { name: '删除节点', exact: true }).click()
      await board.getByRole('dialog', { name: '删除节点', exact: true })
        .getByRole('button', { name: '确认删除', exact: true }).click()
      await canvas.getByRole('button', { name: '对照子节点', exact: true }).waitFor({ state: 'detached' })
      await board.close()
      await tasks.getByText('已完成', { exact: true }).nth(1).waitFor({ timeout: 100000 })
      await tasks.getByText(/Bot 已归档/).waitFor()
      await tasks.getByText('PAPER_ALPHA', { exact: true }).click()
      await tasks.getByText('已核对 PAPER_ALPHA', { exact: true }).waitFor()
      await tasks.getByRole('button', { name: '关闭 项目任务', exact: true }).click()
      await chat.getByText('分派结果已返回', { exact: true }).waitFor({ timeout: 180000 })
      const archive = nav.locator('details').filter({ has: page.getByText('已归档 Bot · 1', { exact: true }) })
      await archive.locator('summary').click()
      await archive.getByRole('button', { name: '原文核对', exact: true }).waitFor()
      await toggle.click()
      const sessionId = await chat.getAttribute('data-conversation-session')
      const status = await page.evaluate(async args => (await fetch('/api/labweave/project', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(args),
      })).status, { sessionId, action: 'bot_cluster', args: { targetId: groupId, memberIds: [memberId] } })
      assert.equal(status, 200)
      const clustered = tasks.locator('section').filter({ has: page.getByRole('heading', { name: '方法证据组', exact: true }) })
      await clustered.getByText(/证据关系 ·/).waitFor()
      await clustered.getByText('PAPER_BETA', { exact: true }).waitFor()
      await tasks.getByText(/Bot 已归档/).waitFor()
      await page.setViewportSize({ width: 850, height: 760 })
      await page.evaluate(() => { document.body.style.zoom = '1.25' })
      await page.emulateMedia({ colorScheme: 'dark' })
      const fits = await tasks.evaluate(dialog => {
        const bounds = dialog.getBoundingClientRect()
        return bounds.left >= 0 && bounds.right <= innerWidth && bounds.bottom <= innerHeight
      })
      assert.ok(fits)
      await tasks.getByRole('button', { name: '定时任务', exact: true }).click()
      await tasks.getByText('本项目的 Bot 暂无定时任务。', { exact: true }).waitFor()
    } catch (error) {
      console.error((await page.locator('body').innerText()).slice(-1800))
      throw error
    }
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(error.message); process.exitCode = 1 })
